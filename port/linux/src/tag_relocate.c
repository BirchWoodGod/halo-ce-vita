/* tag_relocate.c

Cache files are linked to the Xbox tag cache address (0x803A6000): tag data
and structure BSPs hold absolute pointers into that 22 MB window. A process
that cannot map the window there (the Vita) loads the data wherever its tag
cache is and adds the difference to every pointer.

Which words are pointers comes from the tag definitions (tag_layouts.h,
generated by tools/gen_tag_layouts.py from Invader's): the walk starts at
the tag index and the BSP header and follows every block, as the game does,
relocating block, data and tag reference pointers and the Xbox-only raw
pointers (model parts, BSP materials). A scan by value would not do: packed
vertex normals and collision BSP indices look like window addresses.

Halo Custom Edition caches are linked to 0x40440000 instead, with a tag
cache of 23 MB (1.5 times that with OpenSauce's memory upgrades); their tags
are moved the same way once custom_edition_cache.c has loaded and converted
them, which leaves them in this build's layouts (halo_tag_relocate_linked_*).

HALO_TAG_RELOCATION_REPORT=1 prints what was relocated; HALO_TAG_DUMP=<dir>
keeps a copy of what was read, before relocation. */

#include <pthread.h>
#include <stdio.h>
#include <stdlib.h>

/* (platform.h's; stderr on Linux, the log on the Vita) */
void platform_log(const char *format, ...);
/* (platform.h's: zeroed memory of its own, xbox_memory.c) */
void *halo_custom_edition_memory_alloc(unsigned long bytes);
void halo_custom_edition_memory_free(void *address);
#include <string.h>

#include "tag_relocate.h"

#define XBOX_TAG_CACHE_BASE 0x803A6000UL
#define XBOX_TAG_CACHE_SIZE 0x01600000UL
#define WINDOW_WORDS (XBOX_TAG_CACHE_SIZE / 4)

enum
{
	_tag_field_block,
	_tag_field_data,
	_tag_field_reference,
	_tag_field_pointer,
	_tag_field_struct
};

struct tag_layout_field
{
	unsigned short offset;
	unsigned char kind;
	/* the element or embedded struct (0xFFFF: one without pointers), and
	a block element's size */
	unsigned short child;
	unsigned long child_size;
};

struct tag_layout_struct
{
	unsigned short first_field;
	unsigned short field_count;
};

struct tag_layout_group
{
	unsigned long group_tag;
	unsigned short root;
};

#include "tag_layouts.h"

#define NO_LAYOUT 0xFFFF

/* one bit per word of the Xbox window: relocated already */
static unsigned char xbox_relocated[WINDOW_WORDS / 8];

static struct
{
	unsigned char *window;
	unsigned long bias;
	/* port: what a relocated pointer is moved by: the bias, but for a
	structure BSP linked elsewhere than it is loaded in the window
	(halo_tag_relocate_linked_structure_bsp_rebase) */
	unsigned long store_bias;
	/* the address the data are linked to, the size of the window there and
	its words */
	unsigned long link_base, link_size, words;
	/* one bit per word of the window: relocated already (xbox_relocated, or
	a Custom Edition window's own) */
	unsigned char *relocated;
	/* the loaded ranges, as Xbox addresses; pointers are followed only
	into them */
	unsigned long tags_end;
	unsigned long bsp_start, bsp_end;
	unsigned long pointers, outside, walked;
	/* port: tag blocks whose count and element pointer are inconsistent with
	the loaded region, and tag references to no loaded tag or to a tag of
	another group than they name (a crafted map): the caller refuses such a
	map */
	unsigned long invalid;
	/* port: the loaded tag instances (32 bytes each, relocated) that tag
	references are checked against; none: not checked */
	unsigned char *instances;
	long instance_count;
	/* (stale references made to name no tag) */
	unsigned long stale;
	int report;
} relocation;

/* (port) one walk at a time: the scene packs' builder moves a Custom
Edition map's tags on a thread of its own (halo_tag_relocate_linked_tags_
isolated) while the game may move a structure bsp's; each public walk holds
this, and the builder's leaves the game's state as it was. tag_validate.c
holds the same lock (halo_tag_walk_lock) */
static pthread_mutex_t tag_walk_mutex = PTHREAD_MUTEX_INITIALIZER;

void halo_tag_walk_lock(void)
{
	pthread_mutex_lock(&tag_walk_mutex);
}

void halo_tag_walk_unlock(void)
{
	pthread_mutex_unlock(&tag_walk_mutex);
}

static int loaded(unsigned long xbox_address)
{
	return (xbox_address >= relocation.link_base && xbox_address < relocation.tags_end) ||
		(xbox_address >= relocation.bsp_start && xbox_address < relocation.bsp_end);
}

/* port: map files are untrusted - whether the whole span [xbox_start,
xbox_start + bytes) lies inside one loaded region, with no overflow, so that
a crafted block count or buffer count cannot walk an array off the end of
the tag cache window (an out-of-bounds read, or a count so large the walk
never ends). */
static int region_fits(unsigned long xbox_start, unsigned long bytes)
{
	unsigned long end = xbox_start + bytes;

	if (end < xbox_start)
	{
		return 0;
	}
	if (xbox_start >= relocation.link_base && end <= relocation.tags_end)
	{
		return 1;
	}
	if (relocation.bsp_end > relocation.bsp_start && xbox_start >= relocation.bsp_start && end <= relocation.bsp_end)
	{
		return 1;
	}
	return 0;
}

/* relocates the pointer at location (inside the window) once; returns where
it points in this process, or NULL when it does not point into the window */
static unsigned char *relocate_word(unsigned char *location)
{
	unsigned long word = (unsigned long)(location - relocation.window) / 4;
	unsigned long value;
	unsigned int stored;

	if (word >= relocation.words)
		return NULL;
	memcpy(&value, location, 4);
	/* (relocated already: where it points in this process, from where it
	was moved to) */
	if (relocation.relocated[word / 8] & (1 << (word % 8)))
		return (unsigned char *)(value - relocation.store_bias + relocation.bias);
	if (value - relocation.link_base >= relocation.link_size)
	{
		if (value)
			relocation.outside++;
		return NULL;
	}
	relocation.relocated[word / 8] |= (unsigned char)(1 << (word % 8));
	relocation.pointers++;
	stored = (unsigned int)(value + relocation.store_bias);
	memcpy(location, &stored, 4);
	return (unsigned char *)(value + relocation.bias);
}

/* port: an inconsistency the walk found (HALO_TAG_RELOCATION_REPORT=1 logs
the first few) */
static void walk_invalid(const char *what, unsigned long a, unsigned long b, unsigned long c)
{
	if (relocation.report && relocation.invalid < 8)
		platform_log("tag-relocate: invalid %s (0x%08lx 0x%08lx 0x%08lx)", what, a, b, c);
	relocation.invalid++;
}

static void walk(unsigned short struct_index, unsigned char *address)
{
	const struct tag_layout_struct *layout = &tag_layout_structs[struct_index];
	unsigned short index;

	relocation.walked++;
	for (index = 0; index < layout->field_count; index++)
	{
		const struct tag_layout_field *field = &tag_layout_fields[layout->first_field + index];
		unsigned char *at = address + field->offset;

		switch (field->kind)
		{
		case _tag_field_block:
		{
			long count;
			unsigned char *elements;

			memcpy(&count, at, 4);
			elements = relocate_word(at + 4);
			/* port: a non-empty tag block must point into the loaded region
			and its whole element array must fit there; a crafted count or
			pointer is flagged (the map is refused) rather than walked off
			the end or left for the game to index out of bounds */
			if (count != 0 && field->child_size > 0)
			{
				if (count < 0 || !elements ||
					(unsigned long)count > relocation.link_size / field->child_size ||
					!region_fits((unsigned long)(elements - relocation.bias), (unsigned long)count * field->child_size))
				{
					walk_invalid("block", (unsigned long)count, (unsigned long)elements, field->child_size);
				}
				else if (field->child != NO_LAYOUT)
				{
					long element;

					for (element = 0; element < count; element++)
						walk(field->child, elements + element * field->child_size);
				}
			}
			break;
		}
		case _tag_field_data:
			relocate_word(at + 12);
			break;
		case _tag_field_reference:
			relocate_word(at + 4);
			/* port: a reference names no tag (NONE) or a loaded one, of the
			group it says (or a group that tag's inherits): checked here,
			once, rather than in every tag_get (tag_groups.h) */
			if (relocation.instances)
			{
				unsigned long group_tag;
				long tag_index;

				memcpy(&group_tag, at, 4);
				memcpy(&tag_index, at + 12, 4);
				if (tag_index != -1)
				{
					short absolute_index = (short)tag_index;
					unsigned char *instance;
					unsigned long instance_groups[3];
					long instance_index;

					if (absolute_index < 0 || absolute_index >= relocation.instance_count)
					{
						walk_invalid("reference index", group_tag, (unsigned long)tag_index, (unsigned long)relocation.instance_count);
						break;
					}
					instance = relocation.instances + absolute_index * 32;
					memcpy(instance_groups, instance, 12);
					memcpy(&instance_index, instance + 12, 4);
					if (group_tag && group_tag != 0xFFFFFFFFUL && instance_groups[0] != group_tag &&
						instance_groups[1] != group_tag && instance_groups[2] != group_tag)
					{
						/* (Bungie's own maps have a few stale references: another
						tag's salt, of another group, which nothing gets - the
						debug builds would assert. Such a one names no tag now;
						one of the tag's own salt but another group is a crafted
						map's) */
						if (((unsigned long)tag_index & 0xFFFF0000UL) && instance_index != tag_index)
						{
							long none = -1;

							memcpy(at + 12, &none, 4);
							relocation.stale++;
						}
						else
						{
							walk_invalid("reference group", group_tag, (unsigned long)tag_index, instance_groups[0]);
						}
					}
				}
			}
			break;
		case _tag_field_pointer:
			relocate_word(at);
			break;
		case _tag_field_struct:
			if (field->child != NO_LAYOUT)
				walk(field->child, at);
			break;
		}
	}
}

/* the vertex or index buffer headers of an array: D3DResource Common,
Data (a pointer), Lock */
static void relocate_buffers(unsigned char *array, long count)
{
	long index;

	/* port: the buffer array (12 bytes each) must fit the loaded region */
	if (!array || count <= 0 || (unsigned long)count > relocation.link_size / 12 ||
		!region_fits((unsigned long)(array - relocation.bias), (unsigned long)count * 12))
		return;
	for (index = 0; index < count; index++)
		relocate_word(array + index * 12 + 4);
}

static void dump(void *data, unsigned long size, const char *name)
{
	const char *directory = getenv("HALO_TAG_DUMP");
	static int dump_index;
	char path[512];
	FILE *file;
	unsigned long xbox_address = (unsigned long)data - relocation.bias;

	if (!directory)
		return;
	snprintf(path, sizeof(path), "%s/%02d-%s.bin", directory, dump_index++, name);
	file = fopen(path, "wb");
	if (file)
	{
		fwrite(&xbox_address, 4, 1, file);
		fwrite(data, 1, size, file);
		fclose(file);
	}
}

static void begin(void *tag_cache)
{
	const char *value = getenv("HALO_TAG_RELOCATION_REPORT");

	relocation.report = value && value[0] == '1';
	relocation.window = tag_cache;
	relocation.bias = (unsigned long)tag_cache - relocation.link_base;
	relocation.store_bias = relocation.bias;
	relocation.pointers = relocation.outside = relocation.walked = relocation.invalid = relocation.stale = 0;
}

static void finish(const char *what, unsigned long size)
{
	if (relocation.report)
		platform_log("tag-relocate: %s: %lu bytes, bias 0x%08lx: %lu pointers relocated, %lu structs walked, "
			"%lu pointer fields outside the window, %lu inconsistencies, %lu stale references", what, size, relocation.bias,
			relocation.pointers, relocation.walked, relocation.outside, relocation.invalid, relocation.stale);
}

/* port: the number of inconsistent tag blocks the last relocation walk
found (a crafted map); the caller refuses the map when it is not zero */
unsigned long halo_tag_relocate_anomalies(void)
{
	return relocation.invalid;
}

static void use_xbox_window(void)
{
	relocation.link_base = XBOX_TAG_CACHE_BASE;
	relocation.link_size = XBOX_TAG_CACHE_SIZE;
	relocation.words = WINDOW_WORDS;
	relocation.relocated = xbox_relocated;
}

/* (called every 32 tags the walk takes: the loading screen's frames while
a Custom Edition map loads, custom_edition_cache.c; NULL: none) */
void (*halo_tag_relocate_progress)(void);

/* the bytes of a struct of a layout the walk reads: to its last field's
end (a block 12, a data 20, a reference 16, a pointer 4, a struct its own) */
static unsigned long layout_extent(unsigned short struct_index, int depth)
{
	const struct tag_layout_struct *layout = &tag_layout_structs[struct_index];
	unsigned long extent = 0;
	unsigned short index;

	if (depth > 32)
		return (unsigned long)-1;
	for (index = 0; index < layout->field_count; index++)
	{
		const struct tag_layout_field *field = &tag_layout_fields[layout->first_field + index];
		unsigned long end = field->offset;

		switch (field->kind)
		{
		case _tag_field_block: end += 12; break;
		case _tag_field_data: end += 20; break;
		case _tag_field_reference: end += 16; break;
		case _tag_field_pointer: end += 4; break;
		case _tag_field_struct:
			end += field->child != NO_LAYOUT ? layout_extent(field->child, depth + 1) : 0;
			break;
		}
		if (end > extent)
			extent = end;
	}
	return extent;
}

/* walks the tags of every instance */
static void relocate_instances(unsigned char *instances, long count)
{
	long index;

	/* port: the instance array (32 bytes each) must fit the loaded tags: a
	crafted tag count cannot send the walk off the end */
	if (!instances || count <= 0 || (unsigned long)count > relocation.link_size / 32 ||
		!region_fits((unsigned long)(instances - relocation.bias), (unsigned long)count * 32))
	{
		relocation.instances = NULL;
		relocation.instance_count = 0;
		return;
	}
	/* (the references the walk meets are checked against these, and so are
	the structure BSPs' later) */
	relocation.instances = instances;
	relocation.instance_count = count;
	for (index = 0; index < count; index++)
	{
		/* group tags x3, tag index, name, base address, unused x2 */
		unsigned char *instance = instances + index * 32;
		unsigned long group_tag;
		unsigned char *base;
		unsigned short group;

		if (halo_tag_relocate_progress && !(index & 31))
			halo_tag_relocate_progress();
		relocate_word(instance + 16);
		base = relocate_word(instance + 20);
		if (!base || !loaded((unsigned long)(base - relocation.bias)))
			continue;
		memcpy(&group_tag, instance, 4);
		for (group = 0; group < sizeof(tag_layout_groups) / sizeof(tag_layout_groups[0]); group++)
		{
			if (tag_layout_groups[group].group_tag == group_tag)
			{
				/* port: and all of the root the walk reads in the loaded
				region (its first byte in it is not enough at the region's end:
				a crafted map's last tag); a root that is not is left for the
				tag check, which refuses it */
				if (tag_layout_groups[group].root != NO_LAYOUT &&
					region_fits((unsigned long)(base - relocation.bias), layout_extent(tag_layout_groups[group].root, 0)))
				{
					walk(tag_layout_groups[group].root, base);
				}
				break;
			}
		}
		if (group == sizeof(tag_layout_groups) / sizeof(tag_layout_groups[0]))
			platform_log("tag-relocate: no layout for tag group '%c%c%c%c'",
				(int)(group_tag >> 24), (int)(group_tag >> 16 & 0xff), (int)(group_tag >> 8 & 0xff), (int)(group_tag & 0xff));
	}
}

static void halo_tag_relocate_tags_unlocked(void *tag_cache, unsigned long size)
{
	unsigned char *header = tag_cache;
	unsigned char *instances;
	long count, vertex_buffer_count, index_buffer_count;

	use_xbox_window();
	begin(tag_cache);
	dump(tag_cache, size, "tags");
	memset(relocation.relocated, 0, relocation.words / 8);
	relocation.tags_end = relocation.link_base + size;
	relocation.bsp_start = relocation.bsp_end = 0;
	/* (a new map's instances: none until relocate_instances finds them) */
	relocation.instances = NULL;
	relocation.instance_count = 0;
	if (!relocation.bias)
		return;
	/* the header: tag instances, count, vertex and index buffers */
	instances = relocate_word(header);
	memcpy(&count, header + 12, 4);
	memcpy(&vertex_buffer_count, header + 16, 4);
	memcpy(&index_buffer_count, header + 24, 4);
	relocate_buffers(relocate_word(header + 20), vertex_buffer_count);
	relocate_buffers(relocate_word(header + 28), index_buffer_count);
	if (!instances)
		return;
	relocate_instances(instances, count);
	finish("tags", size);
}

/* the Custom Edition window's own bits, kept from its tags to its
structure BSPs */
static unsigned char *linked_relocated;
static unsigned long linked_base, linked_size, linked_tags_end;

static int halo_tag_relocate_linked_tags_unlocked(void *tag_cache, unsigned long size, unsigned long link_base,
	unsigned long window_bytes)
{
	unsigned char *header = tag_cache;
	unsigned char *instances;
	long count;

	/* (in memory of its own, zeroed, rather than the C heap, of which the
	Vita has a fixed 48 MB that the system's libraries share: 736 KB for a
	23 MB window) */
	halo_tag_relocate_linked_release();
	linked_relocated = halo_custom_edition_memory_alloc(window_bytes / 32 + 1);
	if (!linked_relocated)
		return 0;
	linked_base = link_base;
	linked_size = window_bytes;
	relocation.link_base = link_base;
	relocation.link_size = window_bytes;
	relocation.words = window_bytes / 4;
	relocation.relocated = linked_relocated;
	begin(tag_cache);
	relocation.tags_end = linked_tags_end = link_base + size;
	relocation.bsp_start = relocation.bsp_end = 0;
	relocation.instances = NULL;
	relocation.instance_count = 0;
	if (!relocation.bias)
		return 1;
	/* the Custom Edition tag index: tag instances, scenario, checksum,
	count, then model data offsets and sizes (no pointers) */
	instances = relocate_word(header);
	memcpy(&count, header + 12, 4);
	if (instances)
		relocate_instances(instances, count);
	finish("custom edition tags", size);
	return 1;
}

static void halo_tag_relocate_linked_structure_bsp_unlocked(void *tag_cache, void *bsp, unsigned long size)
{
	unsigned char *header = bsp;
	unsigned char *structure;
	unsigned long start_word, end_word, word;

	if (!linked_relocated)
		return;
	relocation.link_base = linked_base;
	relocation.link_size = linked_size;
	relocation.words = linked_size / 4;
	relocation.relocated = linked_relocated;
	relocation.tags_end = linked_tags_end;
	begin(tag_cache);
	relocation.bsp_start = (unsigned long)bsp - relocation.bias;
	relocation.bsp_end = relocation.bsp_start + size;
	if (!relocation.bias)
		return;
	start_word = (unsigned long)(header - relocation.window) / 4;
	end_word = start_word + (size + 3) / 4;
	if (end_word > relocation.words)
		end_word = relocation.words;
	for (word = start_word; word < end_word; word++)
		relocation.relocated[word / 8] &= (unsigned char)~(1 << (word % 8));
	/* the Custom Edition header: the BSP tag, then no Xbox vertex buffers */
	structure = relocate_word(header);
	if (structure && loaded((unsigned long)(structure - relocation.bias)))
		walk(TAG_LAYOUT_STRUCTURE_BSP, structure);
	finish("custom edition structure bsp", size);
}

/* port: A Halo: CE Anniversary map's structure BSP (custom_edition_cache.c)
is read into its tag cache at to_link, as the tags are linked, but its own
pointers are linked to from_link, where MCC loads it: they are moved to
to_link (with a walk of their own: the BSP's layout, its pointers into
itself alone), and then as any other structure BSP's (above). */
static void halo_tag_relocate_linked_structure_bsp_rebase_unlocked(void *bsp, unsigned long size, unsigned long from_link,
	unsigned long to_link)
{
	unsigned char *header = bsp;
	unsigned char *structure;
	unsigned char *relocated;
	unsigned char *instances = relocation.instances;
	long instance_count = relocation.instance_count;

	if (size < 0x18 || size > 0x10000000UL)
		return;
	relocated = halo_custom_edition_memory_alloc(size / 32 + 1);
	if (!relocated)
	{
		/* (its pointers stay where they point: the game finds the bsp's
		blocks outside the tag cache and refuses it) */
		platform_log("tag-relocate: out of memory moving a structure bsp");
		return;
	}
	relocation.link_base = from_link;
	relocation.link_size = size;
	relocation.words = size / 4;
	relocation.relocated = relocated;
	begin(bsp);
	relocation.store_bias = to_link - from_link;
	/* (pointers are followed into the bsp alone; references are checked
	against the tags' instances, as the bsp's later walk does) */
	relocation.tags_end = from_link;
	relocation.bsp_start = from_link;
	relocation.bsp_end = from_link + size;
	relocation.instances = instances;
	relocation.instance_count = instance_count;
	structure = relocate_word(header);
	if (structure && loaded((unsigned long)(structure - relocation.bias)))
		walk(TAG_LAYOUT_STRUCTURE_BSP, structure);
	finish("halo: ce anniversary structure bsp moved", size);
	halo_custom_edition_memory_free(relocated);
	relocation.instances = instances;
	relocation.instance_count = instance_count;
}

void halo_tag_relocate_linked_release(void)
{
	halo_custom_edition_memory_free(linked_relocated);
	linked_relocated = NULL;
}

static void halo_tag_relocate_structure_bsp_unlocked(void *tag_cache, void *bsp, unsigned long size)
{
	unsigned char *header = bsp;
	unsigned char *structure;
	unsigned long start_word, end_word, word;
	long vertex_buffer_count, lightmap_vertex_buffer_count;

	use_xbox_window();
	begin(tag_cache);
	dump(bsp, size, "bsp");
	relocation.bsp_start = (unsigned long)bsp - relocation.bias;
	relocation.bsp_end = relocation.bsp_start + size;
	if (!relocation.bias)
		return;
	/* this BSP replaces whatever was loaded there before */
	start_word = (unsigned long)(header - relocation.window) / 4;
	end_word = start_word + (size + 3) / 4;
	if (end_word > relocation.words)
		end_word = relocation.words;
	for (word = start_word; word < end_word; word++)
		relocation.relocated[word / 8] &= (unsigned char)~(1 << (word % 8));
	/* the header: the BSP tag, vertex buffers, lightmap vertex buffers */
	structure = relocate_word(header);
	memcpy(&vertex_buffer_count, header + 4, 4);
	memcpy(&lightmap_vertex_buffer_count, header + 12, 4);
	relocate_buffers(relocate_word(header + 8), vertex_buffer_count);
	relocate_buffers(relocate_word(header + 16), lightmap_vertex_buffer_count);
	if (structure && loaded((unsigned long)(structure - relocation.bias)))
		walk(TAG_LAYOUT_STRUCTURE_BSP, structure);
	finish("structure bsp", size);
}

/* ---------- (port) scene packs (port/linux/game/scene_pack.c)

A scene pack's tags are laid out as a map's tag data (a tag header, its
table, names, vertex and index buffers, the tags), linked to a link base of
their own, and read into the tag cache wherever there is room. The builder
walks the tags it copies by these layouts, so that it moves every pointer
the walk below follows; the loader moves them with the walk itself, with
every pointer followed only into the pack and every reference checked
against the pack's own table, and refuses the pack if any is wrong. The
map's own walk state (its window's bits, its table for the structure bsps'
references) is kept as it was. */

unsigned short halo_tag_layout_root(unsigned long group_tag)
{
	unsigned short group;

	for (group = 0; group < sizeof(tag_layout_groups) / sizeof(tag_layout_groups[0]); group++)
	{
		if (tag_layout_groups[group].group_tag == group_tag)
			return tag_layout_groups[group].root;
	}
	return HALO_TAG_LAYOUT_UNKNOWN;
}

long halo_tag_layout_field_count(unsigned short layout)
{
	if (layout >= sizeof(tag_layout_structs) / sizeof(tag_layout_structs[0]))
		return 0;
	return tag_layout_structs[layout].field_count;
}

int halo_tag_layout_field(unsigned short layout, long index, struct halo_tag_layout_field *field)
{
	const struct tag_layout_field *source;

	if (layout >= sizeof(tag_layout_structs) / sizeof(tag_layout_structs[0]) || index < 0 ||
		index >= tag_layout_structs[layout].field_count)
	{
		return 0;
	}
	source = &tag_layout_fields[tag_layout_structs[layout].first_field + index];
	field->offset = source->offset;
	field->kind = source->kind;
	field->child = source->child;
	field->child_size = source->child_size;
	return 1;
}

static unsigned long halo_tag_relocate_pack_unlocked(void *blob, unsigned long size, unsigned long link_base)
{
	unsigned char *header = blob;
	long index;
	unsigned char *instances;
	unsigned char *bits;
	long count, vertex_buffer_count, index_buffer_count;
	unsigned long anomalies;
	/* (the map's walk, as it was: the structure bsps' loads go on from it) */
	int saved_report = relocation.report;
	unsigned char saved[sizeof(relocation)];

	if (!blob || size < 0x24 || (size & 3) || size > 0x01000000UL || link_base + size < link_base)
		return 1;
	bits = malloc(size / 32 + 1);
	if (!bits)
		return (unsigned long)-1;
	memset(bits, 0, size / 32 + 1);
	memcpy(saved, &relocation, sizeof(relocation));
	relocation.link_base = link_base;
	relocation.link_size = size;
	relocation.words = size / 4;
	relocation.relocated = bits;
	begin(blob);
	relocation.report = saved_report || relocation.report;
	relocation.tags_end = link_base + size;
	relocation.bsp_start = relocation.bsp_end = 0;
	relocation.instances = NULL;
	relocation.instance_count = 0;
	/* (a pack read where it is linked: nothing to move, but every pointer
	is still checked by the walk's bounds, below) */
	if (!relocation.bias)
		relocation.store_bias = 0;
	instances = relocate_word(header);
	memcpy(&count, header + 12, 4);
	memcpy(&vertex_buffer_count, header + 16, 4);
	memcpy(&index_buffer_count, header + 24, 4);
	/* (the header's arrays must fit the pack: relocate_buffers and
	relocate_instances pass over ones that do not, which is a refusal here) */
	if (!instances || count <= 0 || (unsigned long)count > size / 32 ||
		!region_fits((unsigned long)(instances - relocation.bias), (unsigned long)count * 32))
	{
		walk_invalid("pack instances", (unsigned long)count, (unsigned long)instances, size);
	}
	if (vertex_buffer_count < 0 || index_buffer_count < 0 ||
		(unsigned long)vertex_buffer_count > size / 12 || (unsigned long)index_buffer_count > size / 12)
	{
		walk_invalid("pack buffers", (unsigned long)vertex_buffer_count, (unsigned long)index_buffer_count, size);
	}
	else
	{
		unsigned char *vertex_buffers = relocate_word(header + 20);
		unsigned char *index_buffers = relocate_word(header + 28);

		if ((vertex_buffer_count && (!vertex_buffers ||
				!region_fits((unsigned long)(vertex_buffers - relocation.bias), (unsigned long)vertex_buffer_count * 12))) ||
			(index_buffer_count && (!index_buffers ||
				!region_fits((unsigned long)(index_buffers - relocation.bias), (unsigned long)index_buffer_count * 12))))
		{
			walk_invalid("pack buffer arrays", (unsigned long)vertex_buffers, (unsigned long)index_buffers, size);
		}
		else
		{
			relocate_buffers(vertex_buffers, vertex_buffer_count);
			relocate_buffers(index_buffers, index_buffer_count);
		}
	}
	/* (each tag's root, all the walk reads of it, in the pack: the walk
	checks blocks' elements whole, but a root only by its first byte, which
	a map's tag cache window covers past its tags and a pack does not) */
	for (index = 0; index < count && !relocation.invalid; index++)
	{
		unsigned char *instance = instances + index * 32;
		unsigned long group_tag, base;
		unsigned short root;

		memcpy(&group_tag, instance, 4);
		memcpy(&base, instance + 20, 4);
		root = halo_tag_layout_root(group_tag);
		if (root == HALO_TAG_LAYOUT_UNKNOWN ||
			(root != NO_LAYOUT && (base < link_base || !region_fits(base, layout_extent(root, 0)))))
		{
			walk_invalid("pack tag root", group_tag, base, size);
		}
	}
	if (!relocation.invalid)
	{
		relocate_instances(instances, count);
		/* (every tag's name in the pack too) */
		for (index = 0; index < count && !relocation.invalid; index++)
		{
			unsigned char *instance = instances + index * 32;
			unsigned long group_tag, name, base;

			memcpy(&group_tag, instance, 4);
			memcpy(&name, instance + 16, 4);
			memcpy(&base, instance + 20, 4);
			if (halo_tag_layout_root(group_tag) == HALO_TAG_LAYOUT_UNKNOWN ||
				!region_fits(name - relocation.bias, 1) || !region_fits(base - relocation.bias, 4))
			{
				walk_invalid("pack tag", group_tag, name, base);
			}
		}
	}
	finish("scene pack tags", size);
	anomalies = relocation.invalid;
	memcpy(&relocation, saved, sizeof(relocation));
	free(bits);
	return anomalies;
}

