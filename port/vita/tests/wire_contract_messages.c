/*
WIRE_CONTRACT_MESSAGES.C

The wire contract test's message probe (tools/wire_contract.py): built once
against each tree's packet table (its source/networking/network_messages.c,
included here, and the encoder under it, source/memory/data_packet*.c,
data_encoding.c, byte_swapping.c) with the game's flags, it encodes every
message type of that tree, as create_network_game_message does, from two
structures (all zeros; then each byte its index modulo 3, small enough for
the fields that are counts) and prints, a line each:

  <type> <structure size> <zeros: hex or "fail"> <pattern: hex or "fail">

The script compares the lines of this tree with those of the pinned OpenCE
checkout: a shared message must encode to the same bytes. Built with the
game's flags (DEBUG) and the network fuzz targets' stand-ins for the rest
of the game (net_fuzz_game.h).
*/

