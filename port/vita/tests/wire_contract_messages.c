void _exit(int status);

/* the message encoded, in hex, or "fail" when it does not encode (a
structure's count past its field's, which the encoder asserts: the
encoding runs in a child process, whose failure is the type's "fail") */
static void print_encoded(short type, byte const *structure, long size)
{
	static char text[2 * HALO_PORT_NETWORK_PACKET_SIZE + 16];
	int descriptors[2];
	int process;
	int status = 1;
	long length = 0;
	long got;

	if (pipe(descriptors) != 0)
		abort();
	process = fork();
	if (process == 0)
	{
		byte *message;
		long index;
		long message_size;
		static char hex[2 * HALO_PORT_NETWORK_PACKET_SIZE + 16];

		close(descriptors[0]);
		message = create_network_game_message(type, structure, (short)size);
		if (!message)
			_exit(1);
		/* (the header's length and type too: the bytes as they go on the
		wire, after the header's swap) */
		message_size = GET_MESSAGE_SIZE(*(message_header *)message);
		for (index = 0; index < message_size; index++)
		{
			hex[2 * index] = "0123456789abcdef"[message[index] >> 4];
			hex[2 * index + 1] = "0123456789abcdef"[message[index] & 15];
		}
		write(descriptors[1], hex, (unsigned long)(2 * message_size));
		_exit(0);
	}
	close(descriptors[1]);
	while ((got = read(descriptors[0], text + length, sizeof(text) - 1 - length)) > 0)
		length += got;
	close(descriptors[0]);
	waitpid(process, &status, 0);
	text[length] = 0;
	if (status != 0 || length == 0)
		__builtin_printf(" fail");
	else
		__builtin_printf(" %s", text);
}

int main(void)
{
	struct data_packet_group_definition *group = &data_0030aa68.group;
	short type;

	initialize_network_game_packets();
	for (type = 0; type < group->packet_type_count; type++)
	{
		long size;
		byte *structure;
		long index;

		if (!group->packets[type].definition)
		{
			__builtin_printf("%d 0 none none\n", type);
			continue;
		}
		size = type < (short)NUMBEROF(wire_contract_sizes) ? wire_contract_sizes[type] : group->packets[type].definition->size;
		structure = __builtin_malloc((size_t)size + 16);
		__builtin_printf("%d %ld", type, size);
		/* (before the children: what is buffered is printed once) */
		fflush(0);
		memset(structure, 0, (size_t)size);
		print_encoded(type, structure, size);
		for (index = 0; index < size; index++)
			structure[index] = (byte)(index % 3);
		print_encoded(type, structure, size);
		__builtin_printf("\n");
		__builtin_free(structure);
	}

	return 0;
}
